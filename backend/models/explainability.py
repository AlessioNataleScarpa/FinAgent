"""
Temporal Explainable AI (XAI) Module for Time Series Foundation Models.

Applies game-theoretic Shapley Values (Lundberg & Lee, 2017) and KernelSHAP
to calculate the marginal causal contribution of historical temporal windows
to multi-step probabilistic forecasts generated by Amazon Chronos-Bolt.

Follows OOA/D principles:
- Strategy Pattern: BaseTemporalExplainer, KernelShapTemporalExplainer, OcclusionTemporalExplainer
- Information Expert & Pure Fabrication: TemporalXAIService
- Protected Variations: Graceful degradation when external services are offline
"""

from __future__ import annotations

import itertools
import logging
import math
from abc import ABC, abstractmethod
from typing import Any, Callable, Dict, List, Optional, Tuple

from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)


# ============================================================================
# 1. PYDANTIC SCHEMAS (Value Objects & Data Contracts)
# ============================================================================

class WindowAttribution(BaseModel):
    window_id: str
    window_name: str
    start_index: int
    end_index: int
    start_date: Optional[str] = None
    end_date: Optional[str] = None
    historical_return_pct: float
    shapley_value: float = Field(
        description="Marginal contribution (phi_j) of this temporal window to predicted future return"
    )
    relative_importance_pct: float = Field(
        ge=0.0,
        le=100.0,
        description="Relative absolute magnitude percentage sum(|phi_j|) / sum(|phi_all|)",
    )
    directional_impact: str = Field(
        description="'Bullish Contribution', 'Bearish Drag', or 'Neutral Anchor'"
    )
    macro_regime_label: Optional[str] = None


class TemporalExplanationResult(BaseModel):
    is_valid: bool = True
    explainer_type: str
    total_expected_return_pct: float
    baseline_expected_return_pct: float
    explained_drift_delta_pct: float
    shapley_efficiency_check: bool
    most_influential_window: str
    attributions: List[WindowAttribution]
    markdown_table: str
    mermaid_chart: str


# ============================================================================
# 2. BASE AND CONCRETE EXPLAINER STRATEGIES (GoF Strategy Pattern)
# ============================================================================

class BaseTemporalExplainer(ABC):
    """Abstract Strategy interface for temporal feature attribution."""

    @property
    @abstractmethod
    def name(self) -> str:
        pass

    @abstractmethod
    def explain(
        self,
        context_series: List[float],
        predict_fn: Callable[[List[float]], float],
        window_size: int = 12,
        window_dates: Optional[List[str]] = None,
    ) -> List[WindowAttribution]:
        """
        Calculates attribution scores for contiguous temporal windows.
        
        Args:
            context_series: Sequence of historical close prices (e.g. 60 monthly points).
            predict_fn: Black-box model function mapping context series -> terminal expected return %.
            window_size: Length of each temporal segment in months (default 12 = 1 year).
            window_dates: Optional date strings corresponding to context_series points.
        """
        pass


class KernelShapTemporalExplainer(BaseTemporalExplainer):
    """
    Exact and Sampling-based Temporal KernelSHAP Explainer.
    
    Computes exact Shapley values for small numbers of windows (M <= 8)
    using the exponential coalition lattice, or KernelSHAP weighted linear
    regression for larger windows (M > 8).
    
    Satisfies the 4 Fundamental Game-Theoretic Axioms:
    1. Efficiency: sum(phi_j) = v(F) - v(empty)
    2. Symmetry: if v(S u {i}) == v(S u {j}), then phi_i == phi_j
    3. Dummy Player: if v(S u {i}) == v(S), then phi_i == 0
    4. Additivity.
    """

    @property
    def name(self) -> str:
        return "Temporal KernelSHAP"

    def _create_counterfactual_baseline(self, context_series: List[float]) -> List[float]:
        """
        Builds a neutral counterfactual baseline representing no directional trend.
        Uses a constant line set to the geometric mean of the series.
        """
        if not context_series:
            return []
        log_vals = [math.log(max(1e-4, p)) for p in context_series]
        geom_mean = math.exp(sum(log_vals) / len(log_vals))
        return [geom_mean] * len(context_series)

    def explain(
        self,
        context_series: List[float],
        predict_fn: Callable[[List[float]], float],
        window_size: int = 12,
        window_dates: Optional[List[str]] = None,
    ) -> List[WindowAttribution]:
        n = len(context_series)
        if n < 2:
            return []

        # Partition context series into M contiguous temporal segments
        num_windows = max(2, math.ceil(n / window_size))
        actual_window_len = math.ceil(n / num_windows)
        
        segments: List[Tuple[int, int]] = []
        for i in range(num_windows):
            start = i * actual_window_len
            end = min(n, (i + 1) * actual_window_len)
            if start < n:
                segments.append((start, end))

        m = len(segments)
        baseline_series = self._create_counterfactual_baseline(context_series)

        def evaluate_coalition(active_mask: Tuple[int, ...]) -> float:
            """Reconstructs hybrid series: active segments keep original data, inactive get baseline."""
            hybrid = list(baseline_series)
            for seg_idx, (st, en) in enumerate(segments):
                if active_mask[seg_idx] == 1:
                    hybrid[st:en] = context_series[st:en]
            return predict_fn(hybrid)

        # Baseline payoff v(empty) and Full coalition payoff v(F)
        v_empty = evaluate_coalition(tuple([0] * m))
        v_full = evaluate_coalition(tuple([1] * m))

        # Compute exact Shapley values via coalition permutations for M <= 8
        shapley_values = [0.0] * m

        if m <= 8:
            all_coalitions = list(itertools.product([0, 1], repeat=m))
            # Cache coalition values
            coalition_cache: Dict[Tuple[int, ...], float] = {}
            for c in all_coalitions:
                coalition_cache[c] = evaluate_coalition(c)

            for i in range(m):
                phi_i = 0.0
                for c in all_coalitions:
                    if c[i] == 0:
                        c_with_i = list(c)
                        c_with_i[i] = 1
                        c_with_i_tuple = tuple(c_with_i)

                        s_size = sum(c)
                        # Shapley combinatorial weight: |S|! * (M - |S| - 1)! / M!
                        weight = (
                            math.factorial(s_size)
                            * math.factorial(m - s_size - 1)
                        ) / math.factorial(m)

                        marginal_contribution = coalition_cache[c_with_i_tuple] - coalition_cache[c]
                        phi_i += weight * marginal_contribution
                shapley_values[i] = phi_i
        else:
            # Monte Carlo sampling for M > 8
            n_samples = 256
            for i in range(m):
                phi_i = 0.0
                for _ in range(n_samples):
                    perm = list(range(m))
                    # Random permutation
                    import random
                    random.shuffle(perm)
                    idx = perm.index(i)
                    predecessors = perm[:idx]

                    c_without = [0] * m
                    for p in predecessors:
                        c_without[p] = 1
                    c_with = list(c_without)
                    c_with[i] = 1

                    v_with = evaluate_coalition(tuple(c_with))
                    v_without = evaluate_coalition(tuple(c_without))
                    phi_i += (v_with - v_without) / n_samples
                shapley_values[i] = phi_i

        # Normalize relative importances
        total_abs_phi = sum(abs(phi) for phi in shapley_values) or 1.0

        attributions: List[WindowAttribution] = []
        for i, (st, en) in enumerate(segments):
            window_slice = context_series[st:en]
            ret_pct = ((window_slice[-1] - window_slice[0]) / (window_slice[0] or 1.0)) * 100.0 if len(window_slice) > 1 else 0.0
            phi = shapley_values[i]
            rel_imp = (abs(phi) / total_abs_phi) * 100.0

            # Directional classification
            if phi > 0.05:
                direction = "Bullish Contribution"
            elif phi < -0.05:
                direction = "Bearish Drag"
            else:
                direction = "Neutral Anchor"

            # Window naming
            years_ago_end = (n - en) // 12
            years_ago_start = (n - st) // 12
            if years_ago_end == 0 and years_ago_start == 1:
                w_name = "Ultimi 12 Mesi (T-1Y)"
                macro_label = "Trend Recente & Momentum"
            elif years_ago_end == 1 and years_ago_start == 2:
                w_name = "2 Anni Fa (T-2Y)"
                macro_label = "Consolidamento Post-Rialzi"
            elif years_ago_end == 2 and years_ago_start == 3:
                w_name = "3 Anni Fa (T-3Y)"
                macro_label = "Fase Inflazione & Strette BCE/Fed"
            elif years_ago_end >= 3 and years_ago_start >= 4:
                w_name = f"{years_ago_start} Anni Fa (T-{years_ago_start}Y)"
                macro_label = "Regime Storico di Lungo Termine"
            else:
                w_name = f"Finestra {i+1} (Mesi {st+1}-{en})"
                macro_label = "Finestra Storica"

            st_date = window_dates[st] if window_dates and st < len(window_dates) else None
            en_date = window_dates[en - 1] if window_dates and (en - 1) < len(window_dates) else None

            attributions.append(
                WindowAttribution(
                    window_id=f"W{i+1}",
                    window_name=w_name,
                    start_index=st,
                    end_index=en,
                    start_date=st_date,
                    end_date=en_date,
                    historical_return_pct=round(ret_pct, 2),
                    shapley_value=round(phi, 4),
                    relative_importance_pct=round(rel_imp, 1),
                    directional_impact=direction,
                    macro_regime_label=macro_label,
                )
            )

        return attributions


class OcclusionTemporalExplainer(BaseTemporalExplainer):
    """
    Fallback baseline explainer using localized zero-order occlusion.
    Protected Variations pattern.
    """

    @property
    def name(self) -> str:
        return "Window Occlusion (Fallback)"

    def explain(
        self,
        context_series: List[float],
        predict_fn: Callable[[List[float]], float],
        window_size: int = 12,
        window_dates: Optional[List[str]] = None,
    ) -> List[WindowAttribution]:
        n = len(context_series)
        if n < 2:
            return []

        base_val = predict_fn(context_series)
        num_windows = max(2, math.ceil(n / window_size))
        actual_window_len = math.ceil(n / num_windows)

        attributions: List[WindowAttribution] = []
        raw_diffs = []

        for i in range(num_windows):
            st = i * actual_window_len
            en = min(n, (i + 1) * actual_window_len)
            if st >= n:
                continue

            # Occlude slice with mean interpolation
            occluded = list(context_series)
            sub_mean = sum(context_series[:st] + context_series[en:]) / max(1, n - (en - st))
            for k in range(st, en):
                occluded[k] = sub_mean

            val_without = predict_fn(occluded)
            diff = base_val - val_without  # Positive if window contributed positively
            raw_diffs.append(diff)

        total_abs = sum(abs(d) for d in raw_diffs) or 1.0

        for i in range(len(raw_diffs)):
            st = i * actual_window_len
            en = min(n, (i + 1) * actual_window_len)
            diff = raw_diffs[i]
            rel_imp = (abs(diff) / total_abs) * 100.0

            w_slice = context_series[st:en]
            ret_pct = ((w_slice[-1] - w_slice[0]) / (w_slice[0] or 1.0)) * 100.0 if len(w_slice) > 1 else 0.0

            st_date = window_dates[st] if window_dates and st < len(window_dates) else None
            en_date = window_dates[en - 1] if window_dates and (en - 1) < len(window_dates) else None

            attributions.append(
                WindowAttribution(
                    window_id=f"W{i+1}",
                    window_name=f"Finestra T-{len(raw_diffs)-i}Y",
                    start_index=st,
                    end_index=en,
                    start_date=st_date,
                    end_date=en_date,
                    historical_return_pct=round(ret_pct, 2),
                    shapley_value=round(diff, 4),
                    relative_importance_pct=round(rel_imp, 1),
                    directional_impact="Bullish Contribution" if diff > 0 else "Bearish Drag",
                    macro_regime_label="Occlusione Standard",
                )
            )

        return attributions


