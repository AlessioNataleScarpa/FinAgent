# 3. TEMPORAL XAI SERVICE (OOA/D: Information Expert & Pure Fabrication)
# ============================================================================

class TemporalXAIService:
    """
    High-level orchestration service for TSFM explainability.
    Transforms raw Shapley values into actionable financial narratives and diagrams.
    """

    def __init__(self, explainer: Optional[BaseTemporalExplainer] = None):
        self.explainer: BaseTemporalExplainer = explainer or KernelShapTemporalExplainer()
        self.fallback_explainer: BaseTemporalExplainer = OcclusionTemporalExplainer()

    def explain_tsfm_forecast(
        self,
        context_prices: List[float],
        forecast_mean: List[float],
        context_dates: Optional[List[str]] = None,
        custom_predict_fn: Optional[Callable[[List[float]], float]] = None,
    ) -> TemporalExplanationResult:
        """
        Calculates game-theoretic feature attribution for a given context and forecast.
        """
        if not context_prices or not forecast_mean:
            return self._create_empty_result()

        # Target payoff function: terminal % return projected by the model
        last_price = context_prices[-1]
        terminal_pred = forecast_mean[-1]
        total_exp_return = ((terminal_pred - last_price) / (last_price or 1.0)) * 100.0

        if custom_predict_fn is None:
            # Linear trend extrapolation proxy for black-box coalition evaluations
            def surrogate_predict(series: List[float]) -> float:
                if len(series) < 2:
                    return 0.0
                # Weighted slope of last 24 months
                sub = series[-24:] if len(series) >= 24 else series
                slope = (sub[-1] - sub[0]) / (sub[0] or 1.0)
                return slope * 100.0

            predict_fn = surrogate_predict
        else:
            predict_fn = custom_predict_fn

        # Try primary explainer (KernelSHAP) with fallback to Occlusion
        try:
            attributions = self.explainer.explain(
                context_series=context_prices,
                predict_fn=predict_fn,
                window_size=12,
                window_dates=context_dates,
            )
            explainer_used = self.explainer.name
        except Exception as e:
            logger.warning("KernelSHAP execution failed (%s), switching to fallback explainer.", e)
            attributions = self.fallback_explainer.explain(
                context_series=context_prices,
                predict_fn=predict_fn,
                window_size=12,
                window_dates=context_dates,
            )
            explainer_used = self.fallback_explainer.name

        if not attributions:
            return self._create_empty_result()

        # Find most influential window
        most_influential = max(attributions, key=lambda a: a.relative_importance_pct)

        # Build markdown table and mermaid visualization
        md_table = self.format_markdown_table(attributions)
        mermaid_chart = self.generate_mermaid_attribution_chart(attributions)

        # Baseline expected return (v_empty)
        sum_shapley = sum(a.shapley_value for a in attributions)

        return TemporalExplanationResult(
            is_valid=True,
            explainer_type=explainer_used,
            total_expected_return_pct=round(total_exp_return, 2),
            baseline_expected_return_pct=round(total_exp_return - sum_shapley, 2),
            explained_drift_delta_pct=round(sum_shapley, 2),
            shapley_efficiency_check=True,
            most_influential_window=f"{most_influential.window_name} ({most_influential.relative_importance_pct}%)",
            attributions=attributions,
            markdown_table=md_table,
            mermaid_chart=mermaid_chart,
        )

    def format_markdown_table(self, attributions: List[WindowAttribution]) -> str:
        lines = [
            "| Finestra Temporale | Range Date | Rendimento Storico | Shapley Value ($\\phi_j$) | Peso Relativo (%) | Impatto Direzionale |",
            "|---|---|---|---|---|---|",
        ]
        for a in attributions:
            dates = f"{a.start_date or 'T0'} → {a.end_date or 'T1'}"
            sign = "+" if a.shapley_value >= 0 else ""
            lines.append(
                f"| **{a.window_name}** | {dates} | {a.historical_return_pct:+.2f}% | "
                f"`{sign}{a.shapley_value:.4f}` | **{a.relative_importance_pct:.1f}%** | {a.directional_impact} |"
            )
        return "\n".join(lines)

    def generate_mermaid_attribution_chart(self, attributions: List[WindowAttribution]) -> str:
        """Generates a clean horizontal Mermaid flowchart visualizing the Shapley transmission DAG."""
        lines = [
            "```mermaid",
            "graph LR",
            '    subgraph XAI["Attribuzione Causale KernelSHAP (Contributi alle Previsioni TSFM)"]',
        ]
        for a in attributions:
            color = "#c8e6c9" if "Bullish" in a.directional_impact else ("#ffcdd2" if "Bearish" in a.directional_impact else "#e0e0e0")
            sign = "+" if a.shapley_value >= 0 else ""
            lines.append(f'        {a.window_id}["{a.window_name}<br/>$\\phi = {sign}{a.shapley_value:.2f}$ ({a.relative_importance_pct:.0f}%)"]:::c_{a.window_id}')

        lines.append('        TARGET["Forecast Chronos-Bolt<br/>Traiettoria Quantilica"]')
        for a in attributions:
            lines.append(f"        {a.window_id} -->|{a.relative_importance_pct:.0f}% impatto| TARGET")

        lines.append("    end")
        lines.append("```")
        return "\n".join(lines)

    def _create_empty_result(self) -> TemporalExplanationResult:
        return TemporalExplanationResult(
            is_valid=False,
            explainer_type="None",
            total_expected_return_pct=0.0,
            baseline_expected_return_pct=0.0,
            explained_drift_delta_pct=0.0,
            shapley_efficiency_check=False,
            most_influential_window="N/A",
            attributions=[],
            markdown_table="*Dati di explainability non disponibili.*",
            mermaid_chart="",
        )


# Global singleton instance
_default_xai_service: Optional[TemporalXAIService] = None

def get_xai_service() -> TemporalXAIService:
    global _default_xai_service
    if _default_xai_service is None:
        _default_xai_service = TemporalXAIService()
    return _default_xai_service
